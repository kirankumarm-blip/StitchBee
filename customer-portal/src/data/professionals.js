export function calculateDistanceKm(lat1, lon1, lat2, lon2) {
  const R = 6371;
  const dLat = (lat2 - lat1) * (Math.PI / 180);
  const dLon = (lon2 - lon1) * (Math.PI / 180);
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos(lat1 * (Math.PI / 180)) *
      Math.cos(lat2 * (Math.PI / 180)) *
      Math.sin(dLon / 2) *
      Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return Number((R * c).toFixed(1));
}

export function getAllProfessionals(extraTailors = []) {
  const map = new Map();
  CURATED_TAILORS.forEach((item) => {
    map.set(item.id, { ...item });
  });

  if (Array.isArray(extraTailors)) {
    extraTailors.forEach((t) => {
      if (!t || !t.id) return;
      const existing = map.get(t.id);
      if (existing) {
        map.set(t.id, {
          ...existing,
          ...t,
          verified: existing.verified || t.status === 'approved',
          reviewsCount: t.reviewsCount ?? t.reviews ?? existing.reviewsCount,
          categoryLabel: t.categoryLabel || existing.categoryLabel,
          categories: Array.isArray(t.categories) && t.categories.length > 0 ? t.categories : existing.categories,
        });
      }
    });
  }

  return Array.from(map.values());
}

export function findProfessionalById(id, extraTailors = []) {
  if (!id) return null;
  const all = getAllProfessionals(extraTailors);
  return all.find((p) => p.id === id) || null;
}
